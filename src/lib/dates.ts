// Calendar dates as ISO strings 'YYYY-MM-DD': the one place that does date
// arithmetic. Pure (no React, no Dexie), so plain Node can test it.

/** Today's date in the device's own time zone. */
export function todayISO(d = new Date()): string {
  const tz = d.getTimezoneOffset() * 60000
  return new Date(d.getTime() - tz).toISOString().slice(0, 10)
}

/** Shifts an ISO date by whole days (UTC noon, so DST never skips a day). */
export function shiftISO(iso: string, days: number): string {
  const d = new Date(`${iso}T12:00:00Z`)
  d.setUTCDate(d.getUTCDate() + days)
  return d.toISOString().slice(0, 10)
}

/** Whole calendar days from `from` to `to` (negative when `to` is earlier). */
export function daysBetween(from: string, to: string): number {
  return Math.round((Date.parse(`${to}T12:00:00Z`) - Date.parse(`${from}T12:00:00Z`)) / 86_400_000)
}
